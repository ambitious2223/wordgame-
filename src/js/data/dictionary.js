/** @type {readonly string[]} */
export const ARABIC_DICTIONARY = Object.freeze(
  [...new Set(RAW_WORDS.map((word) => normalizeArabic(word)).filter((word) => word.length >= 3 && word.length <= 5))]
);

const DICTIONARY_SET = new Set(ARABIC_DICTIONARY);

/**
 * @param {string} word
 * @returns {boolean}
 */
export function isDictionaryWord(word) {
  return DICTIONARY_SET.has(normalizeArabic(word));
}

/**
 * @param {readonly string[]} wordLetters
 * @param {readonly string[]} pool
 * @returns {boolean}
 */
function canFormFrom(wordLetters, pool) {
  const remaining = [...pool];
  for (const letter of wordLetters) {
    const index = remaining.indexOf(letter);
    if (index === -1) return false;
    remaining.splice(index, 1);
  }
  return true;
}

/**
 * Every dictionary word (3-5 letters) that can be formed from the given tiles.
 * @param {readonly string[]} letters
 * @returns {string[]}
 */
export function findFormableWords(letters) {
  const pool = letters.map((letter) => normalizeArabic(letter));
  return ARABIC_DICTIONARY.filter((word) => {
    if (word.length > pool.length) return false;
    return canFormFrom([...word], pool);
  });
}
